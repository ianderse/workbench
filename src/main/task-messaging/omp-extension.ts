/**
 * Task messaging for OMP: a per-run extension file
 * ================================================
 *
 * OMP cannot take MCP servers per run, but it loads extension files per run (`omp -e <file>`;
 * `--no-extensions` still allows explicit `-e` paths). This module writes one into the run's temp
 * dir: it registers `message_task` and `list_parallel_tasks` (same descriptions and parameters as
 * the Claude tools in tools.ts) and its `execute` calls Workbench's local tools server as an MCP
 * client over HTTP (JSON-RPC `tools/call`) with the run's bearer token. So there is one
 * authorization path: the token of `openMcpToolsSession` (task-tools-server.ts), the same one
 * Claude Code gets in `--mcp-config`.
 *
 * Facts verified live against omp 18.12.6 (probe with an `echo_test` tool):
 *  - The file may be plain ESM JavaScript (`.mjs`); the default export is a factory `(pi) => void`.
 *  - `pi.registerTool({ name, label, description, parameters, execute })`; `parameters` can be a
 *    plain JSON Schema object (no TypeBox needed).
 *  - `execute(toolCallId, params, signal)` returns `{ content: [{ type: 'text', text }], details }`;
 *    that text comes back as the tool result (`tool_execution_end` event, role `toolResult`).
 *  - Global `fetch` exists inside the extension.
 *  - `loadMode: 'essential'` puts the tool in the model's top-level tool list. Without it the tool
 *    is "discoverable": with default tools it is only reachable through `read xd://<tool>` /
 *    `write xd://<tool>` devices, which small models rarely find. With `--tools a,b,tool` an
 *    explicit name makes it top-level; with `--tools` lacking it, it is discoverable only.
 *  - OMP adds an `i` (intent) argument to every tool call; `execute` ignores it.
 *  - The tool name in events is the bare name (`message_task`), not `mcp__workbench__message_task`.
 *
 * Not tested: WSL (the server is `127.0.0.1` of Windows; only the `direct` route reaches it, other
 * routes get no extension).
 */
import { writeFile } from 'fs/promises';
import path from 'path';
import type { MessagingMcpServer } from './types';
import { TASK_RUN_TOOLS } from './tools';

/** Longest a call to the tools server may take */
export const OMP_TOOL_CALL_TIMEOUT_MS = 60_000;

export interface OmpExtensionTool {
  name: string;
  description: string;
  inputSchema: Record<string, unknown>;
}

/** The extension's source for a tools server (url + headers) and its tools. Pure. */
export function buildOmpMessagingExtension(
  server: { url: string; headers: Record<string, string> },
  tools: readonly OmpExtensionTool[] = TASK_RUN_TOOLS,
): string {
  const config = {
    url: server.url,
    headers: server.headers,
    timeoutMs: OMP_TOOL_CALL_TIMEOUT_MS,
    tools: tools.map(({ name, description, inputSchema }) => ({ name, description, inputSchema })),
  };
  return `// Generated by Workbench for one task run: Workbench task messaging tools. Do not edit.
const config = ${JSON.stringify(config, null, 2)};

let nextId = 1;

async function callTool(name, args, signal) {
  const timeout = AbortSignal.timeout(config.timeoutMs);
  const response = await fetch(config.url, {
    method: 'POST',
    headers: { ...config.headers, 'Content-Type': 'application/json', Accept: 'application/json, text/event-stream' },
    body: JSON.stringify({ jsonrpc: '2.0', id: nextId++, method: 'tools/call', params: { name, arguments: args } }),
    signal: signal ? AbortSignal.any([signal, timeout]) : timeout,
  });
  if (!response.ok) throw new Error('Workbench tools server answered ' + response.status);
  const body = await response.json();
  if (body.error) throw new Error(String(body.error.message || 'Workbench tools server error'));
  const text = (body.result?.content ?? []).map((part) => part?.text ?? '').join('\\n');
  if (body.result?.isError) throw new Error(text || 'The tool failed');
  return text;
}

export default function (pi) {
  for (const tool of config.tools) {
    pi.registerTool({
      name: tool.name,
      label: tool.name,
      description: tool.description,
      parameters: tool.inputSchema,
      loadMode: 'essential',
      async execute(toolCallId, params, signal) {
        const { i, ...args } = params ?? {};
        const text = await callTool(tool.name, args, signal);
        return { content: [{ type: 'text', text }], details: {} };
      },
    });
  }
}
`;
}

/** Write the extension into `tempDir`; undefined when the server is not reachable over HTTP */
export async function writeOmpMessagingExtension(tempDir: string, server: MessagingMcpServer | undefined): Promise<string | undefined> {
  if (!server || server.type !== 'http') return undefined;
  const file = path.join(tempDir, 'workbench-messaging.mjs');
  await writeFile(file, buildOmpMessagingExtension(server), 'utf-8');
  return file;
}
